create table if not exists public.documents (
  title text primary key,
  content text not null,
  category text default '분류: 미분류',
  author text default '익명',
  updated_at timestamptz not null default now()
);

create table if not exists public.revisions (
  id bigint generated by default as identity primary key,
  title text not null,
  content text not null,
  author text default '익명',
  created_at timestamptz not null default now()
);

create table if not exists public.discussions (
  id bigint generated by default as identity primary key,
  title text not null,
  author text default '익명',
  message text not null,
  created_at timestamptz not null default now()
);

alter table public.documents enable row level security;
alter table public.revisions enable row level security;
alter table public.discussions enable row level security;

drop policy if exists "public read documents" on public.documents;
drop policy if exists "public write documents" on public.documents;
drop policy if exists "public read revisions" on public.revisions;
drop policy if exists "public write revisions" on public.revisions;
drop policy if exists "public read discussions" on public.discussions;
drop policy if exists "public write discussions" on public.discussions;

create policy "public read documents" on public.documents for select using (true);
create policy "public write documents" on public.documents for insert with check (true);
create policy "public update documents" on public.documents for update using (true) with check (true);

create policy "public read revisions" on public.revisions for select using (true);
create policy "public write revisions" on public.revisions for insert with check (true);

create policy "public read discussions" on public.discussions for select using (true);
create policy "public write discussions" on public.discussions for insert with check (true);

